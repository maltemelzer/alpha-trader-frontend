#!/usr/bin/env node
// Copies the Bankiersgrün design system into vendor/bankiersgruen/ and generates tokens.css.
//
// The artifact is private, so this script cannot download it. Claude reads the files with the
// Artifact tool first (they land in a local folder), then runs:
//
//   npm run ds:sync -- <folder that contains project/> [--version <artifact version>]
//
// Source of truth: https://claude.ai/artifact/JTZ2zQxkHrv2m5uZHdqq9C

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ARTIFACT_URL = 'https://claude.ai/artifact/JTZ2zQxkHrv2m5uZHdqq9C';
const NAMESPACE = 'Bankiersgruen';

// published path under project/ → file name in vendor/bankiersgruen/
const FILES = {
  'components/bundle.js': 'bundle.js',
  'components/bundle.css': 'bundle.css',
  'components/index.d.ts': 'index.d.ts',
  'tokens.json': 'tokens.json',
  'README.md': 'README.md',
  'guidelines/diagramme.md': 'diagramme.md',
  'assets/Charts/plotly-template.json': 'plotly-template.json',
  'assets/Charts/plotly-template-farbenblind.json': 'plotly-template-farbenblind.json',
};

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'vendor', 'bankiersgruen');

function fail(msg) {
  console.error(`ds:sync: ${msg}`);
  process.exit(1);
}

function parseArgs(argv) {
  const args = { src: null, version: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--version') args.version = argv[++i];
    else if (!args.src) args.src = argv[i];
    else fail(`unexpected argument "${argv[i]}"`);
  }
  if (!args.src) fail('usage: npm run ds:sync -- <folder containing project/> [--version <v>]');
  return args;
}

function projectDir(src) {
  const abs = resolve(src);
  if (existsSync(join(abs, 'project', 'tokens.json'))) return join(abs, 'project');
  if (existsSync(join(abs, 'tokens.json'))) return abs;
  fail(`no project/tokens.json under ${abs}`);
}

// ---------- tokens.json → tokens.css ----------

const ALIAS = /^\{([A-Za-z0-9][A-Za-z0-9_.-]*)\}$/;

function cssValue(value) {
  const m = typeof value === 'string' && value.match(ALIAS);
  return m ? `var(--${m[1]})` : String(value);
}

export function tokensToCss(tokens) {
  const themes = tokens.color?.themes ?? [];
  const base = themes[0]?.id;
  const rootLines = [];
  const themeLines = Object.fromEntries(themes.slice(1).map((t) => [t.id, []]));

  for (const t of tokens.color?.tokens ?? []) {
    if (typeof t.value === 'string') {
      rootLines.push(`  --${t.name}: ${cssValue(t.value)};`);
      continue;
    }
    rootLines.push(`  --${t.name}: ${cssValue(t.value[base])};`);
    for (const id of Object.keys(themeLines)) {
      if (t.value[id] !== undefined) themeLines[id].push(`  --${t.name}: ${cssValue(t.value[id])};`);
    }
  }

  for (const [name, family] of Object.entries(tokens.type?.families ?? {})) {
    rootLines.push(`  --font-${name}: ${family};`);
  }

  for (const [family, group] of Object.entries(tokens)) {
    if (family === 'color' || family === 'type' || !Array.isArray(group?.tokens)) continue;
    for (const t of group.tokens) rootLines.push(`  --${t.name}: ${cssValue(t.value)};`);
  }

  const typeRules = [];
  for (const group of tokens.type?.groups ?? []) {
    for (const s of group.styles) {
      const decl = [
        `font-family: var(--font-${group.family})`,
        `font-size: ${s.fontSize}`,
        `line-height: ${s.lineHeight}`,
        `font-weight: ${s.fontWeight}`,
      ];
      if (s.letterSpacing) decl.push(`letter-spacing: ${s.letterSpacing}`);
      if (s.name === 'label') decl.push('text-transform: uppercase');
      typeRules.push(`.t-${s.name} { ${decl.join('; ')}; }`);
    }
  }

  const blocks = [
    `/* GENERATED by scripts/sync-design-system.mjs from tokens.json – do not edit. */`,
    `:root {\n  color-scheme: dark;\n${rootLines.join('\n')}\n}`,
    ...Object.entries(themeLines).map(([id, lines]) => `[data-theme="${id}"] {\n${lines.join('\n')}\n}`),
    `/* Type styles */\n${typeRules.join('\n')}`,
  ];
  return blocks.join('\n\n') + '\n';
}

// ---------- main ----------

function main() {
  const { src, version } = parseArgs(process.argv.slice(2));
  const dir = projectDir(src);

  const missing = Object.keys(FILES).filter((p) => !existsSync(join(dir, p)));
  if (missing.length) fail(`missing in ${dir}:\n  ${missing.join('\n  ')}\nRead them with the Artifact tool first.`);

  const bundle = readFileSync(join(dir, 'components/bundle.js'), 'utf8');
  if (!bundle.includes(`window.${NAMESPACE}`)) fail(`bundle.js does not assign window.${NAMESPACE}`);

  let tokens;
  try {
    tokens = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));
  } catch (e) {
    fail(`tokens.json is not valid JSON: ${e.message}`);
  }

  mkdirSync(outDir, { recursive: true });
  const hashes = {};
  for (const [from, to] of Object.entries(FILES)) {
    const buf = readFileSync(join(dir, from));
    writeFileSync(join(outDir, to), buf);
    hashes[to] = createHash('sha256').update(buf).digest('hex');
  }
  writeFileSync(join(outDir, 'tokens.css'), tokensToCss(tokens));

  const source = {
    artifact: ARTIFACT_URL,
    version: version ?? null,
    syncedAt: new Date().toISOString(),
    files: hashes,
  };
  writeFileSync(join(outDir, 'SOURCE.json'), JSON.stringify(source, null, 2) + '\n');

  console.log(`ds:sync: ${Object.keys(FILES).length} files + tokens.css → vendor/bankiersgruen/`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
